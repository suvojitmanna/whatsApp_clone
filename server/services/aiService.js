import User from "../models/user.js";
import {
  META_AI_USER_ID,
  META_AI_AVATAR,
  SYSTEM_PROMPT,
  executeMetaAiWorkflow,
  generateAiImage,
  isImagePrompt,
  extractImagePrompt,
  searchSearxng,
  callDualLlm,
  classifyPromptIntent,
} from "./ai/index.js";

export async function ensureMetaAiUser() {
  try {
    let aiUser = await User.findById(META_AI_USER_ID);
    if (!aiUser) {
      aiUser = await User.findOne({ username: "Meta AI" });
    }
    if (!aiUser) {
      aiUser = new User({
        _id: META_AI_USER_ID,
        username: "Meta AI",
        about:
          "Responses are generated by AI. Some may be inaccurate or inappropriate, including for some teens.",
        isVerified: true,
        isAI: true,
        isOnline: true,
        profilePicture: META_AI_AVATAR,
      });
      await aiUser.save();
    } else {
      let changed = false;
      if (!aiUser.isAI) {
        aiUser.isAI = true;
        changed = true;
      }
      if (!aiUser.isVerified) {
        aiUser.isVerified = true;
        changed = true;
      }
      if (!aiUser.isOnline) {
        aiUser.isOnline = true;
        changed = true;
      }
      if (
        !aiUser.about ||
        aiUser.about.includes("Ask me anything") ||
        aiUser.about.includes("Always here to help")
      ) {
        aiUser.about =
          "Responses are generated by AI. Some may be inaccurate or inappropriate, including for some teens.";
        changed = true;
      }
      if (
        !aiUser.profilePicture ||
        aiUser.profilePicture.includes("wikimedia.org")
      ) {
        aiUser.profilePicture = META_AI_AVATAR;
        changed = true;
      }
      if (changed) await aiUser.save();
    }
    return aiUser;
  } catch (err) {
    console.error("Error ensuring Meta AI user:", err?.message);
    return null;
  }
}

export async function processMetaAiQuery(prompt, chatHistory = []) {
  return await executeMetaAiWorkflow(prompt, chatHistory);
}

export async function generateAiText(prompt, chatHistory = []) {
  const result = await callDualLlm({
    systemPrompt: SYSTEM_PROMPT,
    prompt,
    chatHistory,
  });

  return {
    type: "text",
    content: result.text,
    isMetaAi: true,
  };
}

